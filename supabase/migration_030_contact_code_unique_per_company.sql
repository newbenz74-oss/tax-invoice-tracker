-- รันทั้งไฟล์ผ่าน Supabase SQL Editor ครั้งเดียว ปลอดภัยที่จะรันซ้ำ (idempotent)
--
-- ========================= อาการที่ผู้ใช้เจอ =========================
-- เพิ่มรายชื่อใหม่ในบริษัทหนึ่งแล้วขึ้น "เกิดข้อผิดพลาด" ลอยๆ ทั้งที่กรอกครบถูกต้องทุกช่อง แต่พอเปลี่ยนเป็น
-- ชื่ออื่นกลับเพิ่มได้ตามปกติ — ทำให้เข้าใจผิดว่าเป็นเรื่องความยาวชื่อหรือตัวอักษรพิเศษในชื่อ
--
-- ตัวอย่างจริงที่เจอ (2026-09-30): เพิ่ม "บริษัท คลาวด์ แอนด์ คอมพิวติ้ง (ประเทศไทย) จำกัด" ในบริษัท
-- แอซ เท็ก ไม่ได้ เพราะรหัสที่ระบบสร้างให้คือ "ค-คลาวด์" ซึ่ง **บริษัท ซีบีซอฟท์** ใช้ไปแล้ว
--
-- ========================= ต้นเหตุ =========================
-- constraint เดิม business_partners_contact_code_key เป็น unique (contact_code) เฉยๆ = ห้ามซ้ำทั้ง
-- ฐานข้อมูล ข้ามบริษัทด้วย — เป็นของตกค้างจาก migration_004 ตอนที่ระบบยังรองรับบริษัทเดียว พอ
-- migration_007 เพิ่มการรองรับหลายบริษัทเข้ามา ไม่มีใครกลับมาแก้ข้อนี้
--
-- ผลคือฝั่งหน้าเว็บกับฐานข้อมูลใช้กติกาคนละชุดกัน:
--   - validateContactForm() (lib/contactLogic.ts) เช็ครหัสซ้ำจาก "รายชื่อของบริษัทที่เปิดอยู่" เท่านั้น
--   - generateNextContactCode() (lib/contactLogic.ts) ก็สร้างรหัสโดยดูรายชื่อบริษัทปัจจุบันเท่านั้น
--   - ตัวตรวจไฟล์ Excel นำเข้า (lib/contactExcelImport.ts) ก็เช่นกัน
-- หน้าเว็บจึงบอกว่า "รหัสนี้ว่าง ใช้ได้" แต่ฐานข้อมูลปฏิเสธ — และ error ที่เด้งกลับมาไม่ได้บอกสาเหตุ
--
-- ========================= ทำไมเลือกแก้ที่ฐานข้อมูล ไม่ใช่แก้หน้าเว็บให้เช็คข้ามบริษัท =========================
-- เพราะ "ห้ามซ้ำทั้งระบบ" เป็นกติกาที่ผิดตั้งแต่ต้นสำหรับระบบหลายบริษัท ไม่ใช่แค่หน้าเว็บตรวจไม่ครบ
--
-- เหตุผลจากผู้ใช้ (2026-09-30): "ถ้าฉันรับผิดชอบบริษัท ซีบีซอฟท์ แล้วตั้งรหัส ซ-ซีบี และพนักงานอีกคน
-- รับผิดชอบบริษัท แอซเท็ก จะเพิ่มบริษัท ซีบี ก็จะตั้ง ซ-ซีบี เหมือนกัน" — คนละคนดูแลคนละบริษัท ต่างคน
-- ต่างตั้งรหัสในขอบเขตของตัวเอง ไม่มีทางรู้ (และไม่ควรต้องรู้) ว่าอีกบริษัทใช้รหัสอะไรไปแล้ว
--
-- ถ้าไปแก้ทางตรงข้าม (ให้หน้าเว็บเช็คข้ามบริษัท) จะแย่กว่าเดิม 2 ทาง: ต้องให้ผู้ใช้อ่านรหัสของบริษัทที่
-- ตัวเองไม่มีสิทธิ์เข้าถึง (ขัดกับ RLS ทั้งระบบ) และบริษัทที่มีรายชื่อเยอะจะกินรหัสสวยๆ ไปหมดจนบริษัทเล็ก
-- ตั้งรหัสสั้นๆ ไม่ได้เลย
--
-- ตรวจแล้วว่าไม่มีโค้ดส่วนไหนพึ่งพา "รหัสไม่ซ้ำทั้งระบบ": contact_code ถูกใช้แค่แสดงผล เรียงลำดับ ค้นหา
-- และเช็ครหัสซ้ำ — ทั้งหมดทำงานบนรายชื่อของบริษัทที่เปิดอยู่เท่านั้น ไม่มีจุดไหน query ด้วย contact_code
-- โดยไม่กรอง company_id เลยแม้แต่จุดเดียว

/* ============================== เปลี่ยน constraint ==============================
   ปลอดภัยโดยโครงสร้าง: constraint เดิมห้ามซ้ำทั้งระบบอยู่แล้ว จึงไม่มีทางมีคู่ (company_id, contact_code)
   ที่ซ้ำกันค้างอยู่ก่อน — เปลี่ยนแล้วไม่มีแถวไหนติด ไม่ต้องล้าง/แก้ข้อมูลก่อน

   drop ตัวใหม่ก่อนด้วย เพื่อให้รันไฟล์นี้ซ้ำได้โดยไม่ error ว่า constraint มีอยู่แล้ว */
alter table public.business_partners
  drop constraint if exists business_partners_contact_code_key;

alter table public.business_partners
  drop constraint if exists business_partners_company_contact_code_key;

alter table public.business_partners
  add constraint business_partners_company_contact_code_key
  unique (company_id, contact_code);

comment on column public.business_partners.contact_code is
  'รหัสผู้ติดต่อที่ผู้ใช้ตั้งเอง (ระบบสร้างให้ก่อนแล้วแก้ได้) — ห้ามซ้ำ "ภายในบริษัทเดียวกัน" เท่านั้น ข้ามบริษัทซ้ำกันได้';

/* ============================== ตรวจผลหลังรัน ==============================
   ต้องเหลือ unique constraint ตัวเดียวคือ UNIQUE (company_id, contact_code) */
select conname as ชื่อ_constraint, pg_get_constraintdef(oid) as นิยาม
from pg_constraint
where conrelid = 'public.business_partners'::regclass and contype = 'u';
