-- ========================= เรื่องที่ต้องรู้ =========================
-- total_amount (ยอดรวม VAT) **ยังอยู่เหมือนเดิม ไม่ได้ลบ** — ยังมีประโยชน์ในแง่ "เงินที่จ่ายออกไปจริง"
-- และการลบคอลัมน์ที่เอกสารเก่าอ้างอิงอยู่มีความเสี่ยงมากกว่าประโยชน์ที่ได้

/* ============================== 1. เพิ่มคอลัมน์ ============================== */
alter table public.wht_certificates
  add column if not exists total_amount_excl_vat numeric(14,2);

comment on column public.wht_certificates.total_amount_excl_vat is
  'ยอดเงินที่จ่ายก่อน VAT — ฐานที่ใช้คำนวณภาษีหัก ณ ที่จ่ายจริง (VAT ไม่ใช่เงินได้พึงประเมิน) ใช้แสดงบนใบ ใน PDF และในไฟล์ RD Prep แทน total_amount ซึ่งเป็นยอดรวม VAT — null = ใบเก่าที่ย้อนหาฐานไม่ได้';

/* ============================== 2. เติมย้อนหลังจากรายการที่ยังผูกอยู่ ==============================
   เส้นทางปกติ — ใบส่วนใหญ่ยังมี pending_tax_invoices ผูกอยู่ครบ รวม amount_excl_vat ของรายการเหล่านั้น
   ได้ฐานภาษีที่ถูกต้องตรงตามที่ควรเป็นตั้งแต่แรก */
update public.wht_certificates c
set total_amount_excl_vat = s.base
from (
  select wht_certificate_id, sum(amount_excl_vat) as base
  from public.pending_tax_invoices
  where wht_certificate_id is not null
  group by wht_certificate_id
) s
where c.id = s.wht_certificate_id
  and c.total_amount_excl_vat is null;

/* ============================== 3. เติมให้ใบที่ลิงก์ขาด ==============================
   เงื่อนไขแน่นมากโดยตั้งใจ: ต้องตรงกัน **ทั้งยอดรวมและภาษี** พร้อมกัน และต้องเป็นบริษัทเดียวกัน
   โอกาสที่รายการคนละใบจะบังเอิญตรงกันทั้งสองค่าพร้อมกันแทบเป็นศูนย์ (ยอดมีทศนิยม 2 ตำแหน่งทั้งคู่)
   ถ้าไม่ตรงเป๊ะจะไม่เติมให้ ปล่อยเป็น null ดีกว่าเติมผิด — ฐานภาษีที่ผิดคือตัวเลขที่จะถูกยื่นสรรพากร

   ไม่แตะ wht_certificate_id ของรายการจ่ายเงินโดยตั้งใจ — การ "ผูกกลับ" จะเปลี่ยนสถานะรายการนั้นในหน้า
   บันทึกการจ่ายเงินด้วย ซึ่งเป็นผลข้างเคียงที่ผู้ใช้ไม่ได้ขอ งานของ migration นี้คือเติมฐานภาษีเท่านั้น */
update public.wht_certificates c
set total_amount_excl_vat = i.amount_excl_vat
from public.pending_tax_invoices i
where c.total_amount_excl_vat is null
  and i.company_id = c.company_id
  and i.wht_certificate_id is null
  and i.amount_excl_vat + i.vat_amount = c.total_amount
  and i.wht_amount = c.total_wht_amount;

/* ============================== 4. ตรวจผลหลังรัน ==============================
   ใบที่ total_amount_excl_vat ยังเป็น null คือใบที่ย้อนหาฐานไม่ได้ ต้องกรอกเองที่หน้าเว็บ
   คอลัมน์ "อัตราที่ได้" ควรออกมาเป็นอัตรามาตรฐาน (1/1.5/2/3/5/10%) ถ้าได้เลขแปลกๆ แปลว่ามีบางใบที่
   ฐานภาษีไม่ตรงกับภาษีที่หักไว้จริง ควรตรวจด้วยมือก่อนยื่น */
select cert_number                                   as เลขที่ใบ,
       total_amount                                  as ยอดรวม_vat,
       coalesce(total_amount_excl_vat::text, 'ยังว่าง') as ยอดก่อน_vat,
       total_wht_amount                              as ภาษีหัก,
       case when total_amount_excl_vat is null then '-'
            else round(total_wht_amount / total_amount_excl_vat * 100, 2)::text || ' %' end as อัตราที่ได้
from public.wht_certificates
where status = 'issued'
order by cert_number;
