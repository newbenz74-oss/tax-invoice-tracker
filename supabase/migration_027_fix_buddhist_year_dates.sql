-- ทั้งระบบตกลงกันไว้ว่า "ฐานข้อมูลเก็บปี ค.ศ. เสมอ ส่วนหน้าจอแสดงเป็น พ.ศ. เสมอ" (ดู formatThaiDate ใน
-- lib/thaiDate.ts) แต่เส้นทางนำเข้าจาก Excel (lib/excelImport.ts) แปลง พ.ศ.→ค.ศ. ให้เฉพาะเซลล์ที่เป็น
-- "ข้อความ วว/ดด/ปปปป" เท่านั้น ส่วนเซลล์ที่มาเป็น Date object / เลข serial / ข้อความ YYYY-MM-DD ยังเก็บ
-- ปีตามที่ไฟล์ให้มาตรงๆ ไฟล์บัญชีไทยที่เขียนปีเป็น พ.ศ. จึงถูกบันทึกลงฐานข้อมูลเป็นปี 2569 แทนที่จะเป็น 2026
--
-- อาการที่ผู้ใช้เห็น (แจ้ง 2026-09-15): วันที่บนหน้าจอขึ้นเป็น 30/08/3112 — เพราะชั้นแสดงผลบวก 543 ให้ตาม
-- ปกติ (2569 + 543 = 3112) ทับกับปีที่ผิดอยู่แล้วในฐานข้อมูล
--
-- โค้ดถูกแก้ที่ต้นทางแล้ว (normalizeBuddhistEra ใน lib/excelImport.ts — ย้ายการแปลงไปไว้ที่ทางออกทางเดียว
-- ของฟังก์ชัน ครอบคลุมทุกเส้นทาง) ไฟล์นี้แก้ "ข้อมูลที่นำเข้าไปแล้วก่อนหน้านั้น" ให้ถูกต้องย้อนหลัง
--
-- ============================================================================================
-- ความปลอดภัยของคำสั่งนี้
-- ============================================================================================
-- แตะเฉพาะแถวที่ปี >= 2400 เท่านั้น ซึ่งเป็นไปไม่ได้เลยที่จะเป็น ค.ศ. จริงของเอกสารทางบัญชี (ค.ศ. 2400
-- คือ พ.ศ. 2943 — อีก 374 ปีข้างหน้า) แถวที่ถูกต้องอยู่แล้วจะไม่ถูกแตะแม้แต่แถวเดียว และรันซ้ำกี่ครั้งก็ได้
-- ผลเหมือนเดิมเสมอ (รันรอบสองจะไม่เจอแถวไหนเข้าเงื่อนไขแล้ว)
--
-- **ก่อนรัน** แนะนำให้ดูก่อนว่าจะกระทบกี่แถว ด้วยคำสั่งนี้ (คัดลอกไปรันแยกก่อน):
--
--   select count(*) as จำนวนแถวที่ผิด,
--          min(transaction_date) as เก่าสุด,
--          max(transaction_date) as ใหม่สุด
--   from public.pending_tax_invoices
--   where extract(year from transaction_date) >= 2400;
--
-- ============================================================================================
-- หมายเหตุเรื่องประวัติการใช้งาน
-- ============================================================================================
-- การแก้นี้จะถูกบันทึกลงตาราง audit_logs โดย trigger ตาม migration_026 (หนึ่งแถวต่อหนึ่งใบกำกับภาษี)
-- โดยผู้กระทำจะขึ้นเป็น "ระบบ / ผู้ดูแลฐานข้อมูล" เพราะรันจาก SQL Editor ไม่ได้ผ่านการล็อกอินของผู้ใช้
-- — ตั้งใจให้เป็นแบบนั้น เพราะนี่คือการแก้ข้อมูลจริง ควรมีร่องรอยไว้ตรวจสอบย้อนหลังได้

-- ============================================================================================
-- ⚠️ คอลัมน์ที่ "เป็น พ.ศ. โดยตั้งใจ" — ห้ามแตะเด็ดขาด
-- ============================================================================================
-- pending_tax_invoices.vat_claim_year เก็บเป็นปี พ.ศ. มาตั้งแต่ migration_002 โดยเจตนา (เป็นเดือน/ปีที่
-- ยื่น ภ.พ.30 ซึ่งผู้ใช้เลือกจาก dropdown ที่เป็น พ.ศ. ตรงๆ ไม่ใช่วันที่ปฏิทิน) เช่นเดียวกับ
-- bank_reconcile_reports.period_year ที่มี check constraint บังคับช่วง 2500-2700 อยู่แล้ว
-- ถ้าเผลอลบ 543 ออกจากสองคอลัมน์นี้ รายงานภาษีซื้อกับประวัติการกระทบยอดจะกรองไม่เจอข้อมูลเลยทั้งระบบ

-- วันที่ทำรายการ (บังคับกรอก จึงไม่มี null)
update public.pending_tax_invoices
set transaction_date = transaction_date - interval '543 years'
where extract(year from transaction_date) >= 2400;

-- วันที่คาดว่าจะได้รับใบกำกับภาษี (ไม่บังคับ อาจเป็น null)
update public.pending_tax_invoices
set expected_date = expected_date - interval '543 years'
where expected_date is not null
  and extract(year from expected_date) >= 2400;

-- วันที่ได้รับเอกสารจริง (ไม่บังคับ)
update public.pending_tax_invoices
set received_date = received_date - interval '543 years'
where received_date is not null
  and extract(year from received_date) >= 2400;

-- วันที่บนใบกำกับภาษี (เพิ่มเข้ามาใน migration_002 — ใช้เป็นวันที่หลักของรายงานภาษีซื้อ จึงสำคัญมากที่ต้องถูก)
update public.pending_tax_invoices
set tax_invoice_date = tax_invoice_date - interval '543 years'
where tax_invoice_date is not null
  and extract(year from tax_invoice_date) >= 2400;

-- ตรวจผลหลังรัน: ทั้ง 4 คอลัมน์ต้องเหลือ 0 แถว
select
  count(*) filter (where extract(year from transaction_date) >= 2400) as วันที่ทำรายการที่ยังผิด,
  count(*) filter (where extract(year from expected_date) >= 2400) as วันที่คาดว่าจะได้รับที่ยังผิด,
  count(*) filter (where extract(year from received_date) >= 2400) as วันที่ได้รับที่ยังผิด,
  count(*) filter (where extract(year from tax_invoice_date) >= 2400) as วันที่ใบกำกับภาษีที่ยังผิด
from public.pending_tax_invoices;
