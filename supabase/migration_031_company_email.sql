-- ใช้ CC ไม่ใช่ BCC โดยตั้งใจ: ผู้ถูกหักภาษีควรเห็นว่าบริษัทผู้จ่ายเงินถือสำเนาฉบับนี้อยู่ด้วย และตอบกลับหา
