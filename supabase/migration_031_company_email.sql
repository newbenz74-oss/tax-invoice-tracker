-- การแก้บรรทัดเดียวใน lib/whtCertificateEmail.ts ถ้าภายหลังอยากให้ซ่อน
--
-- ว่างไว้ (null) = ไม่ส่งสำเนา ระบบทำงานเหมือนเดิมทุกประการ จึงไม่กระทบบริษัทที่ยังไม่ได้ตั้งค่า

alter table public.companies
  add column if not exists email text;

comment on column public.companies.email is
  'อีเมลกลางของบริษัทสำหรับรับสำเนา (CC) ใบหัก ณ ที่จ่ายทุกฉบับที่ส่งออกจากระบบ — null = ไม่ส่งสำเนา ตรวจรูปแบบที่ validateCompanySettingsForm ใน lib/companyLogic.ts';

/* ============================== ตรวจผลหลังรัน ==============================
   ต้องเห็นคอลัมน์ email ชนิด text และ nullable */
select column_name as คอลัมน์, data_type as ชนิด, is_nullable as ว่างได้
from information_schema.columns
where table_schema = 'public' and table_name = 'companies' and column_name = 'email';
